#!/usr/bin/env python3
"""Check that ROADMAP.md and the board name the same open epics (#234).

  python3 scripts/check_roadmap.py          print differences, exit 0 (a warning, never a failure)
  python3 scripts/check_roadmap.py --write  rewrite the "Open epics on the board" list in ROADMAP.md from the board

Needs the gh CLI with access to the repo. Without it, the check says so and exits 0."""
import json, pathlib, re, subprocess, sys

REPO = 'agamrafaeli-instinct/hn-1m-explorer'
RM = pathlib.Path(__file__).resolve().parent.parent / 'ROADMAP.md'
A, B = '<!-- epics:start -->', '<!-- epics:end -->'
PAT = re.compile(r'^\[Epic\]\s*-\s*(.+?)\s*-\s*(.+)$')


def board_epics():
    out = subprocess.run(['gh', 'issue', 'list', '-R', REPO, '--label', 'epic', '--state', 'open', '--limit', '200', '--json', 'number,title'], capture_output=True, text=True)
    if out.returncode: return None
    res = {}
    for i in json.loads(out.stdout):
        m = PAT.match(i['title'])
        if m: res[m.group(1)] = (i['number'], m.group(2))
    return res


def section(epics):
    lines = [A, '## Open epics on the board', '', 'Generated by scripts/check_roadmap.py from the board. Do not edit by hand.', '']
    lines += [f'- {k}: {v[1]} (#{v[0]})' for k, v in sorted(epics.items())]
    return '\n'.join(lines + [B]) + '\n'


def listed(text):
    s = text.split(A)[-1].split(B)[0] if A in text else ''
    return set(re.findall(r'^- ([^:]+):', s, re.M))


def main(argv):
    ep = board_epics()
    if ep is None: print('check_roadmap: gh is not available, skipped.'); return 0
    text = RM.read_text()
    if '--write' in argv:
        body = text.split(A)[0].rstrip() + '\n\n' if A in text else text.rstrip() + '\n\n'
        tail = text.split(B, 1)[1] if B in text else ''
        RM.write_text(body + section(ep) + tail); print(f'Wrote {len(ep)} open epics to ROADMAP.md'); return 0
    have = listed(text); miss = sorted(set(ep) - have); gone = sorted(have - set(ep))
    for k in miss: print(f'On the board, not in ROADMAP.md: {k} (#{ep[k][0]})')
    for k in gone: print(f'In ROADMAP.md, not open on the board: {k}')
    print('Roadmap and board agree.' if not (miss or gone) else 'Run: python3 scripts/check_roadmap.py --write')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
